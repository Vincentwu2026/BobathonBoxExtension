// Regenerates src/data/demoDocuments.ts from the running backend API.
//
//   1. In the repo root:   npm run seed-demo && npm run build && npm run web-api
//   2. In frontend/:       npm run sync-demo-data
//
// The bundled copy lets Demo Mode work with no backend at all. The committed file is
// already populated, so this is only needed if the seed script changes.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const API = process.env.WEB_API_URL || 'http://127.0.0.1:8799';
const OUT = fileURLToPath(new URL('../src/data/demoDocuments.ts', import.meta.url));

const res = await fetch(`${API}/api/demo/documents`);
if (!res.ok) {
  console.error(`API returned HTTP ${res.status}. Is "npm run web-api" running?`);
  process.exit(1);
}
const { documents } = await res.json();
if (!Array.isArray(documents) || documents.length === 0) {
  console.error('No demo documents returned. Run "npm run seed-demo" in the repo root first.');
  process.exit(1);
}

// Search snippets and relevance are query-specific, so they are not part of the static copy.
const clean = documents.map(({ snippet: _s, relevance: _r, ...doc }) => ({ ...doc, relevance: null }));

const body = `// GENERATED by scripts/sync-demo-data.mjs from /api/demo/documents. Do not edit by hand.
// Source: scripts/seed-demo-data.ts in the repo root. All names, emails and figures are fictional.
import type { DocumentItem } from '@/types';

export const DEMO_DOCUMENTS: DocumentItem[] = ${JSON.stringify(clean, null, 2)};
`;

writeFileSync(OUT, body, 'utf-8');
console.log(`Wrote ${clean.length} documents to ${OUT}`);
